  ! output vtk around SFCs at given age
  !----------------------------------------------------------------------------
  ! check all SFCs with the age at tout_SFC_Myr and output vtk around them
  !  (default) tout_SFC_Myr =  0.1, 1, 3, 5, 10
  ! similar to output_around_star_at_given_age
  !----------------------------------------------------------------------------
  subroutine output_around_SFC_at_given_age(dt)
    use amr_commons
    use pm_commons
    use hydro_commons


    real(dp), intent(IN) :: dt

    !variables for output SFC
    integer,parameter :: SFCoutput_n_max = 100 !maximum number of SFC output
    integer :: SFCoutput_n_loc, SFCoutput_n_glob !number of SFC for output
    real(dp),dimension(1:3,1:SFCoutput_n_max) :: SFCoutput_pos_loc, SFCoutput_pos_glob !position of SFC for output
    integer,dimension(1:ncpu) :: SFCoutput_n_list !list for number of SFC for output in each cpu


    real(dp)::scale_nH,scale_T2,scale_l,scale_d,scale_t,scale_v
    real(dp) :: SFC_tout_Myr, t0, current_time, birth_time, dteff
    character(LEN=80):: SFC_tout_char
    integer :: iloc, iglob, offset
    integer :: itout
    integer :: i,icpu,info


    !list of ages for output
    integer,parameter :: SFC_Ntout = 5
    real(dp), dimension(1:SFC_Ntout), parameter:: SFC_tout_Myr_list = (/1d-1, 1d0, 3d0, 5d0, 1d1/)
    character(LEN=80), dimension(1:SFC_Ntout), parameter:: SFC_tout_char_list = (/'_100kyr', '_1Myr  ', '_3Myr  ','_5Myr  ','_10Myr '/) !gfortran requires the same length for the char list

    !buffer for MPI send/recv
    integer,dimension(1:max(ncpu,SFCoutput_n_max*3)) :: sbufi,rbufi
    real(dp),dimension(1:max(ncpu,SFCoutput_n_max*3)) :: sbufr,rbufr

    ! Conversion factor from user units to cgs units
    call units(scale_l,scale_t,scale_d,scale_v,scale_nH,scale_T2)


    dteff=dt !dt from input
    if(use_proper_time)then
      dteff=dteff*aexp**2
    endif


    do itout=1,SFC_Ntout
      !SFC_tout_Myr = 1d0 !age for output
      SFC_tout_Myr = SFC_tout_Myr_list(itout) !age for output in Myr
      SFC_tout_char = SFC_tout_char_list(itout) !age for output in char

      ! output time from Myr to code units
      if(use_proper_time)then
        t0=SFC_tout_Myr * 1d6*(365.*24.*3600.)/(scale_t/aexp**2) !star output time (Myr -> code unit)
        current_time=texp
      else
        t0=SFC_tout_Myr * 1d6*(365.*24.*3600.)/scale_t !star output time (Myr -> code unit)
        current_time=t
      endif

      !-------------------------------------
      !get local SFCs for output
      !-------------------------------------
      SFCoutput_n_loc = 0
      do i=1,npartmax ! find particles in each cpu
        if(.not. (is_SFC(typep(i)) .or. is_PSC(typep(i)))) cycle !consider only SFC/PSC
        birth_time=tp(i)

        ! !--------------- KS DEBUG ------------!
        !  print *, "(KS DEBUG), myid, idp", myid, idp(i)
        ! print *, "(KS DEBUG) birth_time, current_time, t0, dteff: ", birth_time, current_time, t0, dteff
        ! print *, "(KS DEBUG) current_time-t0-dteff, birth_time, current_time-t0, cond: ", current_time-t0-dteff, birth_time, current_time-t0, &
        !      ((current_time-dteff-birth_time).lt.t0).and.(t0.le.(current_time-birth_time))
        ! !--------------- KS DEBUG ------------!


        if (((current_time-dteff-birth_time).lt.t0).and.(t0.le.(current_time-birth_time))) then !age (previous step)  < output_time < age (current step)
          SFCoutput_n_loc = SFCoutput_n_loc + 1
          SFCoutput_pos_loc(1:3,SFCoutput_n_loc) = xp(i,1:3)
        end if
      end do

      !-----------------------------------
      ! create global list of SFCs for output
      !-----------------------------------
      !create SFC_ncand_list (global)
      SFCoutput_n_list(:) = 0
      SFCoutput_n_list(myid) = SFCoutput_n_loc
      sbufi(1:ncpu) = SFCoutput_n_list(:)
      call MPI_ALLREDUCE(sbufi,rbufi,ncpu,MPI_INTEGER,MPI_SUM,MPI_COMM_WORLD,info)
      SFCoutput_n_list(:) = rbufi(1:ncpu)
      SFCoutput_n_glob = sum(SFCoutput_n_list) !total number of SFC for output

      !retry with different SFC_tout_Myr if there is no SFC for output
      if (SFCoutput_n_glob == 0) then
        cycle
      end if

      ! check the number of SFC for output
      if (SFCoutput_n_glob > SFCoutput_n_max) then
        write(*,*)'Number of global SFC for output exceeds the maximum ',SFCoutput_n_glob, SFCoutput_n_max
        write(*,*)'stopping...'
        stop
      end if

      !determine offset between local and global lists
      offset = 0
      do icpu = 1, myid-1  ! "do i = 1,0" loop is just skipped (KS MEMO)
        offset = offset + SFCoutput_n_list(icpu)
      end do

      !create global SFC list
      SFCoutput_pos_glob(:,:)=0 !initialization
      do iloc = 1, SFCoutput_n_loc
        iglob = iloc + offset
        SFCoutput_pos_glob(:,iglob) = SFCoutput_pos_loc(:,iloc)
      end do
      do iglob = 1, SFCoutput_n_glob
        sbufr((iglob-1)*3+1) = SFCoutput_pos_glob(1,iglob)
        sbufr((iglob-1)*3+2) = SFCoutput_pos_glob(2,iglob)
        sbufr((iglob-1)*3+3) = SFCoutput_pos_glob(3,iglob)
      end do
      call MPI_ALLREDUCE(sbufr, rbufr, 3*SFCoutput_n_glob, MPI_DOUBLE_PRECISION,MPI_SUM,MPI_COMM_WORLD,info)
      do iglob = 1, SFCoutput_n_glob
        SFCoutput_pos_glob(1,iglob) = rbufr((iglob-1)*3+1)
        SFCoutput_pos_glob(2,iglob) = rbufr((iglob-1)*3+2)
        SFCoutput_pos_glob(3,iglob) = rbufr((iglob-1)*3+3)
      end do


      !-------------------------------------------
      !output vtk based on global list of SFCs
      !-------------------------------------------
      if(myid==1) then
        write(*,'(A, 1P1E10.2, A, I8)') &
          '** KS DEBUG ** (output_around_SFC_at_given_age) output vtk for SFCs at age of ', SFC_tout_Myr, ' Myr: ',  SFCoutput_n_glob
      end if

      do iglob = 1, SFCoutput_n_glob
        call output_around_SFC(iglob, SFCoutput_pos_glob(1:3,iglob), suffix = TRIM(SFC_tout_char))
      end do

    end do


  end subroutine output_around_SFC_at_given_age
  ! output vtk around a star at given ages
  !----------------------------------------------------------------------------
  !  output aournd a star with idp = idp_ugvtk at ages of star_tout_Myr_list
  ! INPUT: dt = delta t at the current ilevel
  ! NOTE:
  !  output if current_time-dt < output_time <= current_time
  !   this is different from the condition for SN explosion where
  !            current_time < explosion_time <= current_time+dt is considered
  !----------------------------------------------------------------------------
  subroutine output_around_star_at_given_age(dt)
    use amr_commons
    use pm_commons
    use hydro_commons

    real(dp), intent(IN) :: dt

    integer::ilevel

    real(dp)::scale_nH,scale_T2,scale_l,scale_d,scale_t,scale_v
    real(dp) :: star_tout_Myr, t0, current_time, birth_time, dteff
    character(LEN=80):: star_tout_char, nchar, prefix
    integer :: iloc, iglob, offset
    integer :: itout
    integer :: idp_found, itout_found
    integer :: i,info




    !list of ages for output
    integer,parameter :: star_Ntout = 33
    real(dp), dimension(1:star_Ntout), parameter:: star_tout_Myr_list = (/1d-3, 1d-2, 1d-1, 1d0, 2d0, 3d0, 4d0, 5d0, 6d0, 7d0, 8d0, 9d0 &
      ,10d0, 11d0, 12d0, 13d0, 14d0, 15d0, 16d0, 17d0, 18d0, 19d0 &
      ,20d0, 30d0, 40d0, 50d0, 60d0, 70d0, 80d0, 90d0, 100d0, 200d0, 300d0/)

    !KS NOTE: gfortran requires the same length for the char list
    character(LEN=80), dimension(1:star_Ntout), parameter:: star_tout_char_list = (/ '_1kyr  ', '_10kyr ', '_100kyr' &
      , '_1Myr  ', '_2Myr  ', '_3Myr  ', '_4Myr  ','_5Myr  ','_6Myr  ','_7Myr  ','_8Myr  ','_9Myr  ', '_10Myr '&
      , '_11Myr ', '_12Myr ', '_13Myr ', '_14Myr ','_15Myr ','_16Myr ','_17Myr ','_18Myr ','_19Myr ', '_20Myr '&
      , '_30Myr ', '_40Myr ','_50Myr ','_60Myr ','_70Myr ','_80Myr ','_90Myr '  , '_100Myr', '_200Myr', '_300Myr'/)

    real(dp),dimension(1:3) :: star_pos


    !buffer for MPI send/recv
    real(dp),dimension(1:3) :: sbufr,rbufr

    if (idp_ugvtk < 0) return !no output if idp_ugvtk is negative


    ! Conversion factor from user units to cgs units
    call units(scale_l,scale_t,scale_d,scale_v,scale_nH,scale_T2)

    !initialize
    idp_found = 0
    itout_found = 0
    star_pos(:)=0

    !-------------------------------------
    !get star with given idp for output
    !-------------------------------------
    do i=1,npartmax ! find particles in each cpu
      if (idp(i) /= idp_ugvtk) cycle !limit to particle with idp = idp_ugvtk
      if (is_DM(typep(i))) cycle !skip DM particles
      !if (tp(i) .le. 0) cycle !avoid DM particles (tp = 0)
      !if (levelp(i) /= ilevel) cycle !limit particle living in ilevel
      birth_time=tp(i)
      !dteff=dtnew(levelp(i)) !individual time steps
      dteff=dt !dt from input
      if(use_proper_time)then
        dteff=dteff*aexp**2
      endif
      ! print '(2(A, I8),A,1PE16.8)', "KS DEBUG myid = ", myid, ", idp_found = ", idp_found, ", birth_time = ", birth_time

      idp_found = 1
      exit
    end do

    !check if the age is in the list of ages
    if (idp_found == 1) then
      do itout=1,star_Ntout
        star_tout_Myr = star_tout_Myr_list(itout) !age for output in Myr

        ! output time from Myr to code units
        if(use_proper_time)then
          t0=star_tout_Myr * 1d6*(365.*24.*3600.)/(scale_t/aexp**2) !star output time (Myr -> code unit)
          current_time=texp
        else
          t0=star_tout_Myr * 1d6*(365.*24.*3600.)/scale_t !star output time (Myr -> code unit)
          current_time=t
        endif

        !** KS WARNING ** I think dteff is slightly different from (texp(now) - texp(perev)) since aexp now is used to calculate teff
        !probably no problem arises unless aexp changes significantly between steps, but IT NEEDS TO BE CHECKED LATER
        if (((current_time-dteff-birth_time).lt.t0).and.(t0.le.(current_time-birth_time))) then !age (previous step)  < output_time < age (current step)
          ! !--------------- KS DEBUG ------------!
          ! print *, "(KS DEBUG) birth_time, current_time, t0, dteff: ", birth_time, current_time, t0, dteff
          ! print *, "(KS DEBUG) current_time-t0-dteff, birth_time, current_time-t0: ", current_time-t0-dteff, birth_time, current_time-t0
          ! !--------------- KS DEBUG ------------!
          star_pos(1:3) = xp(i,1:3)
          itout_found = itout
          exit !抜け出す
        end if
      end do
    end if

    !check globallly if idp & tout is found
    call MPI_ALLREDUCE(MPI_IN_PLACE,itout_found,1,MPI_INTEGER,MPI_SUM,MPI_COMM_WORLD,info)

    ! !---------------------------- KS DEBUG ---------------------------!
    ! if (idp_found == 1 .and. itout_found == 1) then
    !    if(use_proper_time)then
    !          write(*,'(A, I8, 2(A, 1P1E18.10), A)') &
    !            'KS DEBUG (output_around_star_at_given_age, use_proper_time) idp = ', idp_ugvtk, &
    !            ', t_age =  ', (current_time - birth_time)/ (1d6*(365.*24.*3600.)/(scale_t/aexp**2)), &
    !            ' Myr, dt = ' , dteff / (1d6*(365.*24.*3600.)/(scale_t/aexp**2)) , 'Myr'
    !       !print *, "current_time, birth_time: ", current_time, birth_time
    !    else
    !       write(*,'(A, I8, 2(A, 1P1E18.10), A)') &
    !            'KS DEBUG (output_around_star_at_given_age) = ', idp_ugvtk, &
    !            ', t_age =  ', (current_time - birth_time)/ (1d6*(365.*24.*3600.)/scale_t), &
    !            ' Myr, dt = ' , dteff / (1d6*(365.*24.*3600.)/scale_t) , ' Myr'
    !    end if
    ! end if
    ! !---------------------------- KS DEBUG ---------------------------!

    !-------------------------------------------
    !output vtk around star
    !-------------------------------------------
    if (itout_found .ge. 1) then
      !share star position among cpus
      call MPI_ALLREDUCE(MPI_IN_PLACE, star_pos, 3, MPI_DOUBLE_PRECISION,MPI_SUM,MPI_COMM_WORLD,info)
      star_tout_char = star_tout_char_list(itout_found) !age for output in char
      if(idp_found==1) then
        if(use_proper_time)then
          write(*,'(A, I8, A, 1P1E16.8, A, I4,/,2(A, 1P1E16.8),A)') &
            '** KS DEBUG ** (output_around_star_at_given_age, proper time) output vtk for star with idp = ', idp_ugvtk, ' at age of ', &
            (current_time - birth_time)/ (1d6*(365.*24.*3600.)/(scale_t/aexp**2)), ' Myr and with levelp = ', levelp(i),&
            'tout = ', star_tout_Myr, ' Myr, dt = ' , dteff / (1d6*(365.*24.*3600.)/(scale_t/aexp**2)), ' Myr'
        else
          write(*,'(A, I8, A, 1P1E16.8, A, I4,/,2(A, 1P1E16.8),A)') &
            '** KS DEBUG ** (output_around_star_at_given_age, non-proper time) output vtk for star with idp = ', idp_ugvtk, ' at age of ', &
            (current_time - birth_time)/ (1d6*(365.*24.*3600.)/scale_t), ' Myr and with levelp = ', levelp(i),&
            'tout = ', star_tout_Myr, ' Myr, dt = ' , dteff / (1d6*(365.*24.*3600.)/scale_t), ' Myr'
        end if
      end if

      write(nchar,'(I8)') idp_ugvtk
      prefix = 'idp'//TRIM(adjustl(nchar))//TRIM(star_tout_char)
      call output_around_star(prefix, star_pos(1:3))
    end if


  end subroutine output_around_star_at_given_age
