        !     i=(ind-1-Ni*(j-1)-Ni*Nj*(k-1)) + 1
        !     iok(i,j,k)=1                           !set unity for active cell
        !     ug_cell_index(i,j,k)=cell_index(ind1)  !index of active cell
        !     !ug_cell_level(i,j,k)=cell_levl(ind1)   !level of active cell
        !     ug_cell_level(i,j,k)=lev   !level of active cell
        !     ug_cell_cpu(i,j,k)=cc(ind1)          !cpu of active cell


        !     ! !------------------------- KS DEBUG -------------------------!
        !     ! if ((j==Nj/2) .and. (k==Nk/2)) then
        !     !    print '(A,I5,A,I5,A,3I5,A,I8,A,I8)', "(KS DEBUG) myid = ", myid, ", ind1 = ", ind1, ", i,j,k = ", i,j,k, &
        !     !         ", cell_levl(ind1) = ", cell_levl(ind1), ", cell_index(ind1) = ", cell_index(ind1)
        !     !    print '(A,I5,A,I5,A,3I5,A,1PE16.8)', "(KS DEBUG) myid = ", myid, ", ind1 = ", ind1, ", i,j,k = ", i,j,k, &
        !     !         ", ufront(cell_index(ind1),1) = ", ufront(cell_index(ind1),1)
        !     ! end if
        !     ! !------------------------- KS DEBUG -------------------------!
        !   end if
        ! end do !ind1
      end do !ind0

      !MPI communication
      !inheritate higher level data by taking MAX
      call MPI_ALLREDUCE(MPI_IN_PLACE, iok, Ni*Nj*Nk, MPI_INTEGER, MPI_MAX, MPI_COMM_WORLD,info)
      call MPI_ALLREDUCE(MPI_IN_PLACE, ug_cell_index, Ni*Nj*Nk, MPI_INTEGER, MPI_MAX, MPI_COMM_WORLD,info)
      call MPI_ALLREDUCE(MPI_IN_PLACE, ug_cell_level, Ni*Nj*Nk, MPI_INTEGER, MPI_MAX, MPI_COMM_WORLD,info)
      call MPI_ALLREDUCE(MPI_IN_PLACE, ug_cell_cpu, Ni*Nj*Nk, MPI_INTEGER, MPI_MAX, MPI_COMM_WORLD,info)
    end do !lev


    !-----------------------------------------------------
    ! locally store variables
    !-----------------------------------------------------
    do k = 1, Nk
      do j = 1, Nj
        do i = 1, Ni
          if (ug_cell_cpu(i,j,k) /= myid) cycle !store only the data if the corresponding cell belongs to myid

          ! !------------------- KS DEBUG ---------------!
          ! if ((j==Nj/2) .and. (k==Nk/2) ) then
          !    ! print '(A,I5,A,3I5,A,3I8,I8)', "(KS DEBUG) myid = ", myid, ", i,j,k = ", i,j,k,&
          !    !      ", iok, ug_cell_cpu, ug_cell_level, ug_cell_index,  = ", iok(i,j,k), ug_cell_cpu(i,j,k), ug_cell_level(i,j,k), ug_cell_index(i,j,k)
          !    ind_grid_tmp=mod(ug_cell_index(i,j,k)-ncoarse-1,ngridmax)+1     ! grid to which cell belongs
          !    ind_tmp = (ug_cell_index(i,j,k)-ncoarse-1)/ngridmax+1           ! cell position in grid
          !    iz=(ind_tmp-1)/4
          !    iy=(ind_tmp-1-4*iz)/2
          !    ix=(ind_tmp-1-2*iy-4*iz)
          !    xc_tmp(1)=(dble(ix)-0.5D0)*dx_ug
          !    xc_tmp(2)=(dble(iy)-0.5D0)*dx_ug
          !    xc_tmp(3)=(dble(iz)-0.5D0)*dx_ug
          !    print '(A,I5,A,3I5,A,1P3E15.6,A,3I8)', "(KS DEBUG) myid = ", myid, ", i,j,k = ", i,j,k,&
          !         ", cell_position = ", &
          !    xg(ind_grid_tmp,1)+xc_tmp(1), xg(ind_grid_tmp,2)+xc_tmp(2), xg(ind_grid_tmp,3)+xc_tmp(3), &
          !    ", ug_cell_index, ind_grid, ind  = ", ug_cell_index(i,j,k), ind_grid_tmp, ind_tmp

          ! end if
          ! !------------------- KS DEBUG ---------------!


          ug_ufront(i,j,k,1:nvar) = ufront(ug_cell_index(i,j,k),1:nvar)           !hydro variables
          !ug_ufront(i,j,k,1:nvar) = uold(ug_cell_index(i,j,k),1:nvar)           !hydro variables (KS DEBUG)

          ! if (ug_ufront(i,j,k,1) <= 0) &
          !      print *, "(KS DEBUG) non-positive density ilevel, i, j, k, u, myid, cell_level, cell_idx", ilevel, i,j,k, ug_ufront(i,j,k,1), myid, ug_cell_level(i,j,k), ug_cell_index(i,j,k)

#ifdef RT
          if (is_radiation) then
            do ig=1,nGroups
              iNp=iGroups(ig)
              !ug_Np(i,j,k,ig) = scale_Np * rtuold(ug_cell_index(i,j,k),iNp)    !photon density (computed)
              ! TO MODIFIED (merge_ks): rt_c_fraction is a scalar here (ks: per level, VSLA)
              ug_Np(i,j,k,ig) = scale_Np * rt_c_fraction * rtuold(ug_cell_index(i,j,k),iNp)    !photon density (physical)
            end do
          end if
#endif

          if (is_phi) then
            ug_phi(i,j,k) = phi_sync_for_output(ug_cell_index(i,j,k))    !graviational potential
          end if

          !particle density
          if (is_particle) then
            ug_rhoprt(i,j,k,1) = rhoprt(ug_cell_index(i,j,k),1)          !DM density
            ug_rhoprt(i,j,k,2) = rhoprt(ug_cell_index(i,j,k),2)          !star density
          end if

        end do !k
      end do !j
    end do !i

    !-----------------------------------------------------
    ! gather local variables with MPI communications
    ! warning: myid = 1 in Ramses corresponds to rank = 0 in MPI
    !-----------------------------------------------------
    call MPI_ALLREDUCE(MPI_IN_PLACE, ug_ufront, Ni*Nj*Nk*nvar, MPI_DOUBLE_PRECISION, MPI_SUM, MPI_COMM_WORLD,info)

#ifdef RT
    if (is_radiation) then
      call MPI_ALLREDUCE(MPI_IN_PLACE, ug_Np, Ni*Nj*Nk*nGroups, MPI_DOUBLE_PRECISION, MPI_SUM, MPI_COMM_WORLD,info)
    end if
#endif

    if (is_phi) then
      call MPI_ALLREDUCE(MPI_IN_PLACE, ug_phi, Ni*Nj*Nk, MPI_DOUBLE_PRECISION, MPI_SUM, MPI_COMM_WORLD,info)
    end if

    if (is_particle) then
      call MPI_ALLREDUCE(MPI_IN_PLACE, ug_rhoprt, Ni*Nj*Nk*2, MPI_DOUBLE_PRECISION, MPI_SUM, MPI_COMM_WORLD,info)
    end if

    !-----------------------------------------------------
    ! convert data to cgs units
    !-----------------------------------------------------
    if (myid == 1) then
      do k = 1, Nk
        do j = 1, Nj
          do i = 1, Ni
            !nH, v, T2
            nH(i,j,k) = ug_ufront(i,j,k,1)*scale_nH                   !cm-3
            vx(i,j,k) = ug_ufront(i,j,k,2)/ug_ufront(i,j,k,1)*scale_v/1d5 !km/s
            vy(i,j,k) = ug_ufront(i,j,k,3)/ug_ufront(i,j,k,1)*scale_v/1d5 !km/s
            vz(i,j,k) = ug_ufront(i,j,k,4)/ug_ufront(i,j,k,1)*scale_v/1d5 !km/s
            etot = ug_ufront(i,j,k,5)
            ekk=0.5d0*(ug_ufront(i,j,k,2)**2+ug_ufront(i,j,k,3)**2+ug_ufront(i,j,k,4)**2)/ug_ufront(i,j,k,1)
            eth = etot - ekk
            T2 = (gamma-1d0)*(etot-ekk)/ug_ufront(i,j,k,1)*scale_T2


            ! !------------------- KS DEBUG ---------------!
            ! if ((j==Nj/2) .and. (k==Nk/2) ) then
            !    print '(A,I5,A,3I5,3(A,1PE16.8))', "(KS DEBUG) myid = ", myid, ", i,j,k = ", i,j,k,&
            !         ", nH(i,j,k) = ", nH(i,j,k), ", etot = ", etot,  ", T2 = ", T2
            ! end if
            ! !------------------- KS DEBUG ---------------!

            !yi, Zmetal, mu, TK
            Zmetal(i,j,k) = ug_ufront(i,j,k,imetal)/ug_ufront(i,j,k,1)/0.02d0 !Zsun
            yHe = Y*0.25d0/X !X and Y defined in cooling_modlue.f90
#ifdef RT
            yHI(i,j,k) = ug_ufront(i,j,k,iIons-1+ixHI)/ug_ufront(i,j,k,1)
            yHII(i,j,k) = ug_ufront(i,j,k,iIons-1+ixHII)/ug_ufront(i,j,k,1)
            yH2(i,j,k) = (1d0-yHI(i,j,k)-yHII(i,j,k))*0.5d0
            yHeII(i,j,k) = ug_ufront(i,j,k,iIons-1+ixHeII)/ug_ufront(i,j,k,1)*yHe
            yHeIII(i,j,k) = ug_ufront(i,j,k,iIons-1+ixHeIII)/ug_ufront(i,j,k,1)*yHe
#else
            yHI(i,j,k) = 1d0; yHII(i,j,k) = 0d0; yH2(i,j,k) = 0d0   ! no RT: neutral atomic gas
            yHeII(i,j,k) = 0d0; yHeIII(i,j,k) = 0d0
#endif
            yHeI(i,j,k) = yHe - yHeII(i,j,k) - yHeIII(i,j,k)
            yel =yHII(i,j,k)+yHeII(i,j,k)+2*yHeIII(i,j,k)
            mu =(yHI(i,j,k)+yHII(i,j,k)+2.d0*yH2(i,j,k) + 4.d0*yHe) &
              / (yHI(i,j,k)+yHII(i,j,k)+yH2(i,j,k) + yHe + yel)
            TK(i,j,k) = T2 * mu                                  !K

            ! !KS DEBUG
            ! if (j == 8 .and. k == 8) then
            !    print '(A,/,4I8,1P3E16.8)', &
            !         "(KS DEBUG) myid, i, j, k, nH, TK, mu: ", &
            !         myid, i, j, k, nH(i,j,k), TK(i,j,k), mu
            ! end if

          end do
        end do
      end do
    end if

    ! !KS DEBUG
    ! if (myid == 1) then
    !    print *, "(KS DEBUG) xmin, xmax, (xmin+xmax)*0.5d0, xmin_from_cen*scale_l/pc_cgs, ((xmin+xmax)*0.5d0 - 0.5d0)*scale_l/pc_cgs: ",&
    !         xmin, xmax, (xmin+xmax)*0.5d0, xmin_from_cen*scale_l/pc_cgs, ((xmin+xmax)*0.5d0 - 0.5d0)*scale_l/pc_cgs
    !    print *, "(KS DEBUG) (xmin+xmax)*0.5d0, scale_l, pc_cgs, ((xmin+xmax)*0.5d0 - 0.5d0)*scale_l/pc_cgs: ", &
    !    (xmin+xmax)*0.5d0, scale_l, pc_cgs, ((xmin+xmax)*0.5d0 - 0.5d0)*scale_l/pc_cgs
    ! end if



    !-----------------------------------------------------
    ! write vtk data to a file
    !-----------------------------------------------------

    if (myid == 1) then
      ! get filename (ugvtk/[prefix].[nstep].[level].vtk)
      write(nchar,'(I8)') nstep
      write(nchar2,'(I8)') ilevel
      filename = TRIM(SubDir) // '/' // TRIM(ThisPrefix) // '.' // TRIM(ADJUSTL(nchar)) &
        // '.' // TRIM(ADJUSTL(nchar2)) // '.vtk'

      print *, "outputting ", filename

      ! TO ADDED 2026-11-11: the VTK title line carries the set information (levels of the set, steps, NI) so that an
      ! incomplete set (job killed while writing) is recognisable from any one of its files; the file is written
      ! under a temporary name and renamed when every write succeeded (err=999), so a file with the final name is
      ! always complete
      title_str = 'RAMSES uniform-grid data'
      if (present(l_range)) then
        call ugvtk_set_range(l_range, lmin_set, lmax_set)
        write(str1,'(A,I0,A,I0)') ' levels=', lmin_set, '-', lmax_set
        title_str = TRIM(title_str)//TRIM(str1)
      end if
      write(str1,'(A,I0,A,I0,A,I0)') ' nstep_coarse=', nstep_coarse, ' nstep=', nstep, ' NI=', NI_ugvtk
      title_str = TRIM(title_str)//TRIM(str1)
      filename_tmp = TRIM(filename)//'.tmp'

      if (is_binary) then
        lf = char(10) ! line feed character

        !open data file
        open(LUN, file=filename_tmp,form="unformatted",ACCESS='stream',convert='BIG_ENDIAN', status='replace')   ! TO MODIFIED 2026-11-11: temporary name

        !write VTK header
        buffer = "# vtk DataFile Version 4.0"//lf ;     write (LUN, err=999) trim(buffer)
        buffer = TRIM(title_str)//lf   ;     write (LUN, err=999) trim(buffer)   ! TO MODIFIED 2026-11-11: title with the set information
