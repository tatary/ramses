!################################################################
! output_analysis: ugvtk output of patch/ks (merge_ks, 2026-11-14), generated by
! scratchpad make_output_analysis.py from patch/ks/output_analysis.f90.
!
! Nested uniform-grid VTK files ("ugvtk/<prefix>.<nstep>.<level>.vtk", NI_ugvtk^3 cells per
! level, l_range levels down to nlevelmax) around new SFCs (output_around_SFC, star_formation_fg,
! SFC_output_minmass), new Pop III stars (output_around_star, p3_output_minmass), the star with
! idp = idp_ugvtk and SFCs at given ages (output_analysis_data from amr_step: output_around_
! star_at_given_age / output_around_SFC_at_given_age, SFC_output_at_given_age). Fields: nH, T,
! v, Z, ion fractions, photon densities (RT), gravitational potential (phi_sync_for_output,
! saved by amr_step at the first subcycle of every level) and DM/star densities (rhoprt).
!
! Everything is off unless ugvtk=.true. (&OUTPUT_PARAMS; TO ADDED, ks has no master switch).
! Not ported from ks: the fout_* outputs (x-axis line, central box, around sinks/halos,
! density maximum, potential minimum; all -1 in the ks production namelists) and
! output_line_data/rhomaxPosition/phiminPosition. Differences from ks: rt_c_fraction is a
! scalar (ks: per level), non-cosmological runs use texp = t, the Pop III formation output of
! pop3_model 1-3 (ks: write_log_star_formation) is done by ugvtk_note_new_star /
! ugvtk_flush_new_stars with the p3_output_minmass guard (ks applied it to models 4-6 only),
! rhoprt / phi_sync_for_output live here and are allocated only when used.
!################################################################
module output_analysis
  use amr_parameters, only: dp
  use mpi_mod
  implicit none

  logical :: part_dens_update_done

  real(dp),allocatable,dimension(:,:) :: rhoprt   ! density from particles: 1 -> DM, 2 -> star (ks: amr_commons)
  real(dp),allocatable,dimension(:),public :: phi_sync_for_output   ! potential saved at the first subcycle (ks: poisson_commons)

  ! new stars noted at creation (rank-local) and flushed collectively: TO ADDED (merge_ks)
  integer :: nnote = 0
  real(dp),allocatable,dimension(:,:) :: note_pos
  real(dp),allocatable,dimension(:)   :: note_mass
  integer, allocatable,dimension(:)   :: note_idp, note_pop3

  private   ! default
  public output_uniform_data, systemcall_wrapper, output_around_SFC, output_around_star, output_analysis_data, &
    output_around_SFC_at_given_age, output_around_star_at_given_age, &
    ugvtk_note_new_star, ugvtk_flush_new_stars, save_phi_sync_for_output

CONTAINS

  !#######################################################################################
  ! output_analysis_data: called by amr_step at every level; acts at the finest existing level.
  ! ks also dispatched the fout_* outputs here (not ported).
  !#######################################################################################
  subroutine output_analysis_data(ilevel)
    use amr_commons
    implicit none
    integer, intent(IN) :: ilevel

    if (.not. ugvtk) return

    !-------------------------------
    !output only at maximum level
    !-------------------------------
    if(ilevel<nlevelmax) then !maximum possible level?
      if(numbtot(1,ilevel+1) > 0) then !maximum existing level?
        return
      end if
    end if

    call timer('output - analysis_data','start')

    !initialization
    part_dens_update_done = .false. !particle density data will be updated before vtk outpu

    !output around a star at given ages (here, dt = dtnew(ilevel) is the time difference in the last update)
    call output_around_star_at_given_age(dtnew(ilevel))

    !output around SFC at given ages (similar to above subroutine but searching for all SFCs)
    !TO MODIFIED: this output is done for every SFC regardless of SFC_output_minmass and is
    ! by far the most expensive ugvtk output, so it is now guarded by SFC_output_at_given_age
    ! (default .false.). SFC_output_minmass controls the output at the SFC formation only.
    if(SFC_output_at_given_age .and. sf_fg) then
      call output_around_SFC_at_given_age(dtnew(ilevel))
    end if

  end subroutine output_analysis_data

  !#######################################################################################
  ! save_phi_sync_for_output (ks: interpol_phi.f90): copy of phi taken by amr_step at the first
  ! subcycle of every level, so that the potential written by output_uniform_data refers to the
  ! same moment at all levels (phi itself is not synchronised among levels).
  !#######################################################################################
  subroutine save_phi_sync_for_output(ilevel)
    use amr_commons
    use poisson_commons, only: phi
    implicit none
    integer, intent(IN) :: ilevel
    integer::i,ncache,ind,igrid,iskip,istart,ibound
    integer,allocatable,dimension(:)::ind_grid

    if (.not. allocated(phi_sync_for_output)) then
      allocate(phi_sync_for_output(1:ncoarse+twotondim*ngridmax))
      phi_sync_for_output = 0d0
    end if

    do ibound=1,nboundary+ncpu
      if(ibound<=ncpu)then
        ncache=numbl(ibound,ilevel)
        istart=headl(ibound,ilevel)
      else
        ncache=numbb(ibound-ncpu,ilevel)
        istart=headb(ibound-ncpu,ilevel)
      end if
      if(ncache>0)then
        allocate(ind_grid(1:ncache))
        igrid=istart
        do i=1,ncache
          ind_grid(i)=igrid
          igrid=next(igrid)
        end do
        do ind=1,twotondim
          iskip=ncoarse+(ind-1)*ngridmax
          do i=1,ncache
            phi_sync_for_output(ind_grid(i)+iskip)=phi(ind_grid(i)+iskip)
          end do
        end do
        deallocate(ind_grid)
      end if
    end do
  end subroutine save_phi_sync_for_output

  !#######################################################################################
  ! ugvtk_note_new_star / ugvtk_flush_new_stars (TO ADDED, merge_ks): replacement of the ugvtk part
  ! of ks write_log_star_formation. star_formation_fg notes every new particle at creation
  ! (rank-local; only Pop III stars and the star with idp = idp_ugvtk are kept) and flushes at the
  ! collective points where ks called write_log_star_formation: all ranks gather the notes and
  ! call output_around_star for each (prefix Pop3_<k> with the p3_output_minmass guard when
  ! pop3_output, idp<idp_ugvtk> for the chosen star).
  !#######################################################################################
  subroutine ugvtk_note_new_star(ipart)
    use amr_commons
    use pm_commons
    implicit none
    integer, intent(IN) :: ipart
    real(dp),allocatable,dimension(:,:) :: tpos
    real(dp),allocatable,dimension(:)   :: tmass
    integer, allocatable,dimension(:)   :: tidp, tpop3
    integer :: n

    if (.not. ugvtk) return
    if (.not. (is_pop3(typep(ipart)) .or. idp(ipart) == idp_ugvtk)) return
    if (.not. allocated(note_pos)) then
      allocate(note_pos(3,16), note_mass(16), note_idp(16), note_pop3(16))
    else if (nnote == size(note_mass)) then
      n = size(note_mass)
      allocate(tpos(3,2*n), tmass(2*n), tidp(2*n), tpop3(2*n))
      tpos(:,1:n) = note_pos; tmass(1:n) = note_mass; tidp(1:n) = note_idp; tpop3(1:n) = note_pop3
      call move_alloc(tpos, note_pos); call move_alloc(tmass, note_mass)
      call move_alloc(tidp, note_idp); call move_alloc(tpop3, note_pop3)
    end if
    nnote = nnote + 1
    note_pos(1:3,nnote) = xp(ipart,1:3)
    note_mass(nnote) = mp(ipart)
    note_idp(nnote) = idp(ipart)
    note_pop3(nnote) = 0
    if (is_pop3(typep(ipart))) note_pop3(nnote) = 1
  end subroutine ugvtk_note_new_star

  subroutine ugvtk_flush_new_stars(use_current_ufront, pop3_output)
    use amr_commons
    use pm_commons
    implicit none
    logical, intent(IN) :: use_current_ufront   ! ufront already holds the current state (ks: ufront_updated)
    logical, intent(IN) :: pop3_output          ! output around every new Pop III (ks: pop3_model /= 4, 5, 6)
    integer :: ntot, offset, k, info, icpu
    integer, dimension(1:ncpu) :: nlist
    real(dp),allocatable,dimension(:) :: rbuf
    integer, allocatable,dimension(:) :: ibuf
    real(dp)::scale_nH,scale_T2,scale_l,scale_d,scale_t,scale_v,scale_msun
    character(LEN=80) :: nchar, prefix

    if (.not. ugvtk) return
    if (.not. pop3_output .and. idp_ugvtk < 0) then
      nnote = 0
      return
    end if

    ! gather the notes of all ranks (same pattern as the SFC lists of star_formation_fg)
    nlist(:) = 0
    nlist(myid) = nnote
#ifndef WITHOUTMPI
    call MPI_ALLREDUCE(MPI_IN_PLACE, nlist, ncpu, MPI_INTEGER, MPI_SUM, MPI_COMM_WORLD, info)
#endif
    ntot = sum(nlist)
    if (ntot == 0) then
      nnote = 0
      return
    end if
    offset = 0
    do icpu = 1, myid-1
      offset = offset + nlist(icpu)
    end do
    allocate(rbuf(4*ntot), ibuf(2*ntot))
    rbuf = 0d0; ibuf = 0
    do k = 1, nnote
      rbuf(4*(offset+k)-3:4*(offset+k)-1) = note_pos(1:3,k)
      rbuf(4*(offset+k)) = note_mass(k)
      ibuf(2*(offset+k)-1) = note_idp(k)
      ibuf(2*(offset+k)) = note_pop3(k)
    end do
#ifndef WITHOUTMPI
    call MPI_ALLREDUCE(MPI_IN_PLACE, rbuf, 4*ntot, MPI_DOUBLE_PRECISION, MPI_SUM, MPI_COMM_WORLD, info)
    call MPI_ALLREDUCE(MPI_IN_PLACE, ibuf, 2*ntot, MPI_INTEGER, MPI_SUM, MPI_COMM_WORLD, info)
#endif
    nnote = 0

    call units(scale_l,scale_t,scale_d,scale_v,scale_nH,scale_T2)
    scale_msun = scale_d*scale_l**3/1.989d33

    do k = 1, ntot
      if (pop3_output .and. ibuf(2*k) == 1) then
        if (p3_output_minmass < 0 .or. rbuf(4*k)*scale_msun >= p3_output_minmass) then
          write(nchar,'(I8)') k
          prefix = 'Pop3_'//TRIM(adjustl(nchar))
          call output_around_star(prefix, rbuf(4*k-3:4*k-1), use_current_ufront=use_current_ufront)
        end if
      end if
      if (idp_ugvtk >= 0 .and. ibuf(2*k-1) == idp_ugvtk) then
        write(nchar,'(I8)') idp_ugvtk
        prefix = 'idp'//TRIM(adjustl(nchar))
        call output_around_star(prefix, rbuf(4*k-3:4*k-1), use_current_ufront=use_current_ufront)
      end if
    end do
    deallocate(rbuf, ibuf)
  end subroutine ugvtk_flush_new_stars

  subroutine systemcall_wrapper(command, status)
    implicit none
    character(len=*),intent(IN) :: command
    integer,intent(OUT),optional :: status
    integer :: cmdstat
    call execute_command_line(TRIM(command), exitstat=cmdstat)
    if(present(status)) status=cmdstat
  end subroutine systemcall_wrapper

  ! Output around star-forming cloud
  ! From level = max(levelmin, nlevelmax - l_range + 1) to nlevelmax
  ! File name is SFC[iSFC][suffix].[step].[level].vtk
  !
  ! Note:
  !  This routine is supposed to be called by the star_formation routine,
  !  in which uold at ilevel = nlevelmax is converted to primitive vars,
  !  so uold needs to be reverted to the original conservative vars
  !  while outputing data
  ! -----------------------------------------------------------------
  subroutine output_around_SFC(iSFC, pos, suffix, use_current_ufront)
    use amr_commons
    use amr_parameters
    use pm_commons
    use hydro_commons
    use cooling_module
    implicit none

    integer, intent(IN) :: iSFC
    real(dp), dimension(1:3), intent(IN) :: pos
    character(len=*),intent(IN),optional :: suffix

    logical,intent(IN),optional ::  use_current_ufront !use current ufront without updating it
    logical :: is_use_current_ufront

    character(len=3),parameter :: prefix1 = 'SFC'

    character(len=80) :: prefix, nchar
    real(dp) :: halfwidth, fullwidth
    !integer,parameter :: NIug=64   ! num of uniform grids on a side
    !integer,parameter :: NIug=32   ! num of uniform grids on a side
    !integer,parameter :: l_range=10 ! num of levels to be output

    !for debug
    !integer,parameter :: l_range=6 ! num of levels to be output
    !integer,parameter :: l_range=8 ! num of levels to be output
    !integer,parameter :: l_range=10 ! num of levels to be output
    integer,parameter :: l_range=12 ! num of levels to be output
    !integer,parameter :: NIug=64   ! num of uniform grids on a side
    integer:: ilevel
    real(dp) :: dx
    real(dp) :: xmin,ymin,zmin,xmax,ymax,zmax

    real(dp)::scale_nH,scale_T2,scale_l,scale_d,scale_t,scale_v, scale_msun, scale_tyr !KS DEBUG
    real(dp)::scale_u   ! TO ADDED (merge_ks): user units per code unit (boxlen/nx_loc)

    integer ::ncache,ivar,ngrid
    integer ::igrid,i,j,iskip,ind
    real(dp)::d,u,v,w,e,zg
    integer ,dimension(1:nvector),save::ind_grid,ind_cell

    ! !skip writing data at restarting (KS WARNING: output is allowed only at the beginning of amr_step(levelmin) with this line)
    ! if(nstep_coarse==nstep_coarse_old.and.nstep_coarse>0) return

    if (.not. ugvtk) return   ! TO ADDED (merge_ks): master switch of the ugvtk output

    !check if use current ufront
    if (present(use_current_ufront)) then
      is_use_current_ufront = use_current_ufront
    else
      is_use_current_ufront = .false.
    end if

    !force particle dnesity update
    part_dens_update_done = .false.

    !-----------------------------------------------------------------------------------
    ! revert uold at ilevel = nlevelmax to conservative vars (cf. star_formation.f90)
    !-----------------------------------------------------------------------------------
    ilevel = nlevelmax
    ncache=active(ilevel)%ngrid
    do igrid=1,ncache,nvector
      ngrid=MIN(nvector,ncache-igrid+1)
      do i=1,ngrid
        ind_grid(i)=active(ilevel)%igrid(igrid+i-1)
      end do
      do ind=1,twotondim
        iskip=ncoarse+(ind-1)*ngridmax
        do i=1,ngrid
          ind_cell(i)=iskip+ind_grid(i)
        end do
        do i=1,ngrid
          d=uold(ind_cell(i),1)
          u=uold(ind_cell(i),2)
          v=uold(ind_cell(i),3)
          w=uold(ind_cell(i),4)
          e=uold(ind_cell(i),5)*d
          e=e+0.5d0*d*(u**2+v**2+w**2)
          uold(ind_cell(i),1)=d
          uold(ind_cell(i),2)=d*u
          uold(ind_cell(i),3)=d*v
          uold(ind_cell(i),4)=d*w
          uold(ind_cell(i),5)=e
        end do
        do ivar=imetal,nvar
          do i=1,ngrid
            d=uold(ind_cell(i),1)
            w=uold(ind_cell(i),ivar)
            uold(ind_cell(i),ivar)=d*w
          end do
        end do
      end do
    end do

    !--------------- KS DEBUG ---------------!
    ! Conversion factor from user units to cgs units
    call units(scale_l,scale_t,scale_d,scale_v,scale_nH,scale_T2)
    scale_msun=scale_d*scale_l**3/1.989d33
    scale_tyr=scale_t/(365.*24.*3600.)
    if(myid.eq.1)then
      print '(A,I8,1P3E20.12)', &
        'OUTPUT AROUND STAR-FORMING CLOUD: iSFC, pos(:) = ', &
        iSFC, pos(:)
    end if
    !--------------- KS DEBUG ---------------!

    !get prefix
    write(nchar,'(I8)') iSFC
    prefix = TRIM(prefix1) // TRIM(ADJUSTL(nchar))     !SFC[iSFC].

    !add suffix if exists
    if ( present(suffix) ) then
      prefix = TRIM(prefix) // TRIM(suffix)
    endif


    do ilevel=levelmin,nlevelmax
      if (ilevel < nlevelmax - l_range + 1) cycle       !skip if outside l_range levels
      if(numbtot(1,ilevel) == 0) cycle                  !skip if there are no grids in this level

      dx=0.5d0**ilevel
      !fullwidth = dx * (NIug-1)     ! full width of output region
      !       fullwidth = dx * NIug     ! full width of output region
      fullwidth = dx * NI_ugvtk     ! full width of output region
      scale_u = boxlen/dble(icoarse_max-icoarse_min+1)
      halfwidth = 0.5d0 * fullwidth * scale_u ! half width (user units; TO MODIFIED merge_ks)
      if (fullwidth > 1d0) cycle    ! plot region must be smaller than the computational domain
      ! if (myid == 1) then
      !    print '(/,A,I0,A,I0,A,(1P1E9.2),A)', "output_around_sinkparticles: idsink = ", idsink(isink),&
      !         ", ilevel = ",ilevel, ", size = ", fullwidth
      ! end if

      xmin = pos(1) - halfwidth
      xmax = pos(1) + halfwidth
      ymin = pos(2) - halfwidth
      ymax = pos(2) + halfwidth
      zmin = pos(3) - halfwidth
      zmax = pos(3) + halfwidth

      !restrict to computational box (assume 0 < x,y,z < 1)
      xmin = max(xmin,0d0)
      xmax = min(xmax,boxlen)   ! TO MODIFIED (merge_ks): user units
      ymin = max(ymin,0d0)
      ymax = min(ymax,boxlen)
      zmin = max(zmin,0d0)
      zmax = min(zmax,boxlen)


      !call output_uniform_data(xmin,ymin,zmin,xmax,ymax,zmax,ilevel,prefix=prefix)
      call output_uniform_data(xmin,ymin,zmin,xmax,ymax,zmax,ilevel,prefix=prefix,use_current_ufront=is_use_current_ufront, l_range=l_range)   ! TO MODIFIED 2026-11-11
    end do

    !-----------------------------------------------------------------------------------
    ! convert uold at ilevel = nlevelmax again to primitive vars (cf. star_formation.f90)
    !-----------------------------------------------------------------------------------
    ilevel = nlevelmax
    ncache=active(ilevel)%ngrid
    do igrid=1,ncache,nvector
      ngrid=MIN(nvector,ncache-igrid+1)
      do i=1,ngrid
        ind_grid(i)=active(ilevel)%igrid(igrid+i-1)
      end do
      do ind=1,twotondim
        iskip=ncoarse+(ind-1)*ngridmax
        do i=1,ngrid
          ind_cell(i)=iskip+ind_grid(i)
        end do
        do i=1,ngrid
          d=uold(ind_cell(i),1)
          u=uold(ind_cell(i),2)/d
          v=uold(ind_cell(i),3)/d
          w=uold(ind_cell(i),4)/d
          e=uold(ind_cell(i),5)
          e=e-0.5d0*d*(u**2+v**2+w**2)
          uold(ind_cell(i),1)=d
          uold(ind_cell(i),2)=u
          uold(ind_cell(i),3)=v
          uold(ind_cell(i),4)=w
          uold(ind_cell(i),5)=e/d
        end do
        do ivar=imetal,nvar
          do i=1,ngrid
            d=uold(ind_cell(i),1)
            w=uold(ind_cell(i),ivar)/d
            uold(ind_cell(i),ivar)=w
          end do
        end do
      end do
    end do

  end subroutine output_around_SFC
  ! Output around a star
  ! From level = max(levelmin, nlevelmax - l_range + 1) to nlevelmax
  ! File name is star[idp][suffix].[step].[level].vtk
  !
  ! Note:
  !  This routine is supposed to be called by the star_formation routine,
  !  in which uold at ilevel = nlevelmax is converted to primitive vars,
  !  so uold needs to be reverted to the original conservative vars
  !  while outputing data
  ! -----------------------------------------------------------------
  subroutine output_around_star(prefix, pos, use_current_ufront)
    use amr_commons
    use amr_parameters
    use pm_commons
    use hydro_commons
    use cooling_module
    implicit none

    character(len=*),intent(IN) :: prefix
    !integer, intent(IN) :: istar  !idp of the star for output
    real(dp), dimension(1:3), intent(IN) :: pos
    logical,intent(IN),optional ::  use_current_ufront !use current ufront without updating it
    logical :: is_use_current_ufront
    !character(len=4),parameter :: prefix1 = 'idp'
    !character(len=80) :: prefix, nchar
    real(dp) :: halfwidth, fullwidth
    !integer,parameter :: NIug=64   ! num of uniform grids on a side
    !integer,parameter :: NIug=32   ! num of uniform grids on a side
    !integer,parameter :: l_range=10 ! num of levels to be output

    !for debug
    !integer,parameter :: l_range=6 ! num of levels to be output
    !integer,parameter :: l_range=8 ! num of levels to be output
    !integer,parameter :: l_range=10 ! num of levels to be output
    integer,parameter :: l_range=15 ! num of levels to be output
    !integer,parameter :: NIug=64   ! num of uniform grids on a side
    !integer,parameter :: NIug=8   ! num of uniform grids on a side
    !integer,parameter :: NIug=16   ! num of uniform grids on a side
    integer:: ilevel
    real(dp) :: dx
    real(dp) :: xmin,ymin,zmin,xmax,ymax,zmax

    real(dp)::scale_nH,scale_T2,scale_l,scale_d,scale_t,scale_v, scale_msun, scale_tyr !KS DEBUG
    real(dp)::scale_u   ! TO ADDED (merge_ks): user units per code unit (boxlen/nx_loc)

    integer ::ncache,ivar,ngrid
    integer ::igrid,i,j,iskip,ind
    real(dp)::d,u,v,w,e,zg
    integer ,dimension(1:nvector),save::ind_grid,ind_cell


    if (.not. ugvtk) return   ! TO ADDED (merge_ks): master switch of the ugvtk output

    !check if use current ufront
    if (present(use_current_ufront)) then
      is_use_current_ufront = use_current_ufront
    else
      is_use_current_ufront = .false.
    end if

    ! !skip writing data at restarting (KS WARNING: output is allowed only at the beginning of amr_step(levelmin) with this line)
    ! if(nstep_coarse==nstep_coarse_old.and.nstep_coarse>0) return


    !force particle dnesity update
    part_dens_update_done = .false.


    !--------------- KS DEBUG ---------------!
    ! Conversion factor from user units to cgs units
    call units(scale_l,scale_t,scale_d,scale_v,scale_nH,scale_T2)
    scale_msun=scale_d*scale_l**3/1.989d33
    scale_tyr=scale_t/(365.*24.*3600.)
    if(myid.eq.1)then
      print '(A,A,1P3E20.12)', &
        'OUTPUT AROUND STAR: prefix, pos(:) = ', &
        prefix, pos(:)
    end if
    !--------------- KS DEBUG ---------------!

    ! !get prefix
    ! write(nchar,'(I8)') istar
    ! prefix = TRIM(prefix1) // TRIM(ADJUSTL(nchar))     !star[istar].

    ! !add suffix if exists
    ! if ( present(suffix) ) then
    !    prefix = TRIM(prefix) // TRIM(suffix)
    ! endif


    do ilevel=levelmin,nlevelmax
      if (ilevel < nlevelmax - l_range + 1) cycle       !skip if outside l_range levels
      if(numbtot(1,ilevel) == 0) cycle                  !skip if there are no grids in this level

      dx=0.5d0**ilevel
      !fullwidth = dx * (NIug-1)     ! full width of output region
      !       fullwidth = dx * NIug     ! full width of output region
      fullwidth = dx * NI_ugvtk     ! full width of output region
      scale_u = boxlen/dble(icoarse_max-icoarse_min+1)
      halfwidth = 0.5d0 * fullwidth * scale_u ! half width (user units; TO MODIFIED merge_ks)
      if (fullwidth > 1d0) then
        if(myid.eq.1)then
          print *, "ilevel, dx, NI_ugvtk, fullwidth = ", ilevel, dx, NI_ugvtk, fullwidth
          print *, "skip ugvtk output because fullwidth > 1"
        end if
        cycle    ! plot region must be smaller than the computational domain
      end if

      ! if (myid == 1) then
      !    print '(/,A,I0,A,I0,A,(1P1E9.2),A)', "output_around_sinkparticles: idsink = ", idsink(isink),&
      !         ", ilevel = ",ilevel, ", size = ", fullwidth
      ! end if

      xmin = pos(1) - halfwidth
      xmax = pos(1) + halfwidth
      ymin = pos(2) - halfwidth
      ymax = pos(2) + halfwidth
      zmin = pos(3) - halfwidth
      zmax = pos(3) + halfwidth

