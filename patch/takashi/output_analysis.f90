    real(dp),allocatable,dimension(:,:,:,:) :: ug_Np     !photon density [cm-3]
    real(dp),allocatable,dimension(:,:,:) :: ug_phi     !graviational potential
    real(dp),allocatable,dimension(:,:,:,:) :: ug_rhoprt     !particle density


