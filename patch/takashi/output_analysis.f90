  !#######################################################################################
  ! ugvtk_set_range (TO ADDED 2026-11-11): the level range a nest of l_range levels actually gets,
  ! with the same skip conditions as the callers' loops (outside l_range, empty level, region larger
  ! than the box). Empty levels are the finest ones, so the range is contiguous.
  !#######################################################################################
  subroutine ugvtk_set_range(l_range, lmin_set, lmax_set)
    use amr_commons
    use amr_parameters
    implicit none
    integer, intent(IN) :: l_range
    integer, intent(OUT) :: lmin_set, lmax_set
    integer :: ilevel
    lmin_set = -1; lmax_set = -1
    do ilevel=levelmin,nlevelmax
      if (ilevel < nlevelmax - l_range + 1) cycle
      if (numbtot(1,ilevel) == 0) cycle
      if (0.5d0**ilevel * NI_ugvtk > 1d0) cycle
      if (lmin_set < 0) lmin_set = ilevel
      lmax_set = ilevel
    end do
  end subroutine ugvtk_set_range

  !#######################################################################################
  ! ugvtk_finish_file (TO ADDED 2026-11-11): rank 1 only. ok: rename the temporary file to its final
  ! name (rename is atomic, so a file with the final name is always complete); not ok: report the
  ! write error (the caller has deleted the temporary file).
  !#######################################################################################
  subroutine ugvtk_finish_file(tmpname, finalname, ok)
    implicit none
    character(len=*), intent(IN) :: tmpname, finalname
    logical, intent(IN) :: ok
    logical :: exist
    integer :: info
    if (.not. ok) then
      print *, '(output_uniform_data) ERROR: writing '//TRIM(tmpname)//' failed (disk full?); file deleted, run continues'
      return
    end if
#ifdef NOSYSTEM
    call PXFRENAME(TRIM(tmpname), LEN(TRIM(tmpname)), TRIM(finalname), LEN(TRIM(finalname)), info)
#else
    call system('mv -f '//TRIM(tmpname)//' '//TRIM(finalname))
#endif
    inquire(file=finalname, exist=exist)
    if (.not. exist) print *, '(output_uniform_data) ERROR: could not rename '//TRIM(tmpname)//' to '//TRIM(finalname)
  end subroutine ugvtk_finish_file
! set_particle_density/set_part_dens
!
! - set cell variables for particle density (DM and star) from particle data
!     (cf. star_RT_feedback/star_RT_vsweep in rt_spectra.f90)
! - upload the particle density data from higher to lower levels
!------------------------------------------------------------------------------------
  subroutine set_particle_density
    use pm_commons
    use amr_commons
    implicit none
    !---------------------------------------
    integer :: ilevel
    integer:: igrid, jgrid, ipart, jpart, next_part
    integer:: i, ig, ip, npart1, npart2, icpu
    integer,dimension(1:nvector),save:: ind_grid, ind_part, ind_grid_part
    integer :: current_lmax
    !---------------------------------------
    integer::ncache,ngrid,ind,iskip,nsplit,icell
    integer,dimension(1:nvector),save::ind_cell,ind_split
    logical,dimension(1:nvector),save::ok
    integer ::ivar,ind_son,iskip_son
    integer ,dimension(1:nvector),save::igrid_son,ind_cell_son
    real(dp),dimension(1:nvector),save::getx
    !---------------------------------------

    !------------------------------------------------------------------------
    ! obtain particle contribution to density at particle levels
    !------------------------------------------------------------------------

    !get current maximum level
    current_lmax = levelmin
    do ilevel = levelmin, nlevelmax-1
      if(numbtot(1,ilevel+1) == 0)  exit
      current_lmax = ilevel + 1
    end do

    !initialize rhoprt (TO MODIFIED (merge_ks): module array, allocated on first use)
    if (.not. allocated(rhoprt)) allocate(rhoprt(0:ncoarse+twotondim*ngridmax,1:2))
    rhoprt(:,:) = 0d0

    ! Loop over levels
    do ilevel = levelmin, current_lmax
      ! Gather star particles only.
      ! Loop over cpus
      do icpu=1,ncpu
        igrid=headl(icpu,ilevel) ! grid index
        ig=0                     ! index of grid with stars (in ind_grid)
        ip=0                     ! index of star particle   (in ind_part)
        ! Loop over grids
        do jgrid=1,numbl(icpu,ilevel)
          npart1=numbp(igrid)   ! Number of particles in the grid
          npart2=0              ! number of selected (i.e. star) particles

          ! Count star particles in the grid
          if(npart1 > 0)then
            ipart = headp(igrid)        ! particle index

            !KS DEBUG
            !print '(5(A, I8))', "(KS DEBUG) myid = ", myid, ", jgrid = ", jgrid,", igrid = ", igrid, ", numbp(igrid) = ", numbp(igrid), ", headp(igrid) = ", headp(igrid)

            ! Loop over particles
            do jpart = 1, npart1
              ! !--------------------------------- KS DEBUG -----------------------------!
              ! !if (ipart<1) then
              ! if (myid==58) then
              !    print '(7(A, I8))', "(KS DEBUG something starnge) myid = ", myid, ", jgrid = ", jgrid,", igrid = ", igrid, ", numbp(igrid) = ", numbp(igrid), ", headp(igrid) = ", headp(igrid),&
              !         ", tailp(igrid) = ", tailp(igrid), ", jpart = ", jpart , ", ipart = ", ipart
              ! end if
              ! !--------------------------------- KS DEBUG -----------------------------!
              ! Save next particle       <--- Very important !!!
              next_part = nextp(ipart)
              !if( is_star(typep(ipart)).or.is_pop3(typep(ipart)) ) then ! Radiative feedback from Pop III and Pop II stars. - JP
              if(.true.) then                 !Always true (including DM)
                npart2 = npart2+1
              endif
              ipart = next_part        ! Go to next particle
            end do
          endif

          ! Gather star particles within the grid
          if(npart2 > 0)then
            ig = ig+1
            ind_grid(ig) = igrid
            ipart = headp(igrid)
            ! Loop over particles
            do jpart = 1, npart1
              ! Save next particle      <--- Very important !!!
              next_part = nextp(ipart)
              ! Radiative feedback from Pop III and Pop II stars. - JP
              !if( is_star(typep(ipart)).or.is_pop3(typep(ipart)) ) then
              if(.true.) then                 !Always true (including DM)
                if(ig==0)then
                  ig=1
                  ind_grid(ig)=igrid
                end if
                ip = ip+1
                ind_part(ip) = ipart
                ind_grid_part(ip) = ig ! points to grid a star is in
              endif
              if(ip == nvector)then
                call set_part_dens( &
                  ind_grid,ind_part,ind_grid_part,ig,ip,ilevel)
                ip = 0
                ig = 0
              end if
              ipart = next_part  ! Go to next particle
            end do
            ! End loop over particles
          end if
          igrid = next(igrid)   ! Go to next grid
        end do
        ! End loop over grids
        if(ip > 0) then
          call set_part_dens( &
            ind_grid,ind_part,ind_grid_part,ig,ip,ilevel)
        endif
      end do
      ! End loop over cpus

    end do
    ! End loop over levels

    !-----------------------------------------
    ! upload the cell data to lower levels
    ! cf. upload_fine/upl in interpol_hydro.f90
    !-----------------------------------------
    ! Loop over levels
    do ilevel = current_lmax-1, levelmin, -1

      ! Loop over active grids by vector sweeps
      ncache=active(ilevel)%ngrid
      do igrid=1,ncache,nvector
        ngrid=MIN(nvector,ncache-igrid+1)
        do i=1,ngrid
          ind_grid(i)=active(ilevel)%igrid(igrid+i-1)
        end do

        ! Loop over cells
        do ind=1,twotondim
          iskip=ncoarse+(ind-1)*ngridmax
          do i=1,ngrid
            ind_cell(i)=iskip+ind_grid(i)
          end do

          ! Gather split cells
          do i=1,ngrid
            ok(i)=son(ind_cell(i))>0
          end do

          ! Count split cells
          nsplit=0
          do i=1,ngrid
            if(ok(i))nsplit=nsplit+1
          end do

          ! Upload for selected cells
          if(nsplit>0)then
            icell=0
            do i=1,ngrid
              if(ok(i))then
                icell=icell+1
                ind_split(icell)=ind_cell(i)

                !print *, '(KS DEBUG) myid, ind_cell(i)',  myid, ind_cell(i)
              end if
            end do

            !-------------------------------------------
            ! add the density from higher level particles
            !  cf. subroutine upl in interpol_hydro.f90
            !-------------------------------------------
            ! Get child oct index
            do i=1,nsplit
              igrid_son(i)=son(ind_split(i))
            end do

            ! Loop over variables
            do ivar=1,2    !ivar = 1 -> DM, 2 -> star
              getx(1:nsplit)=0.0d0
              do ind_son=1,twotondim
                iskip_son=ncoarse+(ind_son-1)*ngridmax
                do i=1,nsplit
                  ind_cell_son(i)=iskip_son+igrid_son(i)

                  ! print *, '(KS DEBUG) myid, ivar, ind_split(i), igrid_son(i), ind_cell_son(i)',  &
                  !      myid, ivar, ind_split(i), igrid_son(i), ind_cell_son(i)
                end do
                ! Update average
                do i=1,nsplit
                  getx(i)=getx(i)+rhoprt(ind_cell_son(i),ivar)

                  ! !KS DEBUG
                  ! if (getx(i) > 0) then
                  !    print '(A, 4I8,1P2E12.3)', &
                  !         'KS DEBUG (set_particle_density) myid, ilevel+1, ind_split, ivar, rhoprt(ivar), getx: ', &
                  !         myid, ilevel+1, ind_cell_son(i), ivar, rhoprt(ind_cell_son(i),ivar), getx(i)
                  ! end if

                end do
              end do

              ! Scatter result to cells (take sum of the density from higher level and that from the current level)
              do i=1,nsplit
                rhoprt(ind_split(i),ivar)=rhoprt(ind_split(i),ivar) + getx(i)/dble(twotondim)

                ! !KS DEBUG
                ! if (rhoprt(ind_split(i),ivar) > 0) then
                !    print '(A, 4I8,1P2E12.3)', &
                !         'KS DEBUG (set_particle_density) myid, ilevel, ind_split, ivar, rhoprt(ivar), getx: ', &
                !         myid, ilevel, ind_split(i), ivar, rhoprt(ind_split(i),ivar), getx(i)
                ! end if
              end do

            end do
            ! End loop over variables
            !-------------------------------
            !-------------------------------

          end if

        end do
        ! End loop over cells

      end do
      ! End loop over grids

    end do
    ! End loop over levels

    !-----------------------------------------
    ! Update boundaries
    ! cf. rho_fine in rho_fine.f90
    !-----------------------------------------
    ! Loop over levels
    do ilevel = current_lmax-1, levelmin, -1
      ! Update boundaries
      call make_virtual_reverse_dp(rhoprt(1,1),ilevel) !DM density
      call make_virtual_reverse_dp(rhoprt(1,2),ilevel) !star density
    end do


    part_dens_update_done = .true.
  end subroutine set_particle_density


!------------------------------------------------------------------------------------
! add particle mass to cell density variable
!------------------------------------------------------------------------------------
  subroutine set_part_dens(ind_grid,ind_part,ind_grid_part,ng,np,ilevel)
!
! This routine is called by set_particle_density (cf. star_RT_vsweep)
! Compute contribution of each particle to the density of nearest grid cell
! Particle mass is reflected in cells at level ilevel, but it is important
! to know that ilevel-1 cells may also get some mass. This is due
! to star particles that have just crossed to a coarser level.
!
! ind_grid      =>  grid indexes in amr_commons (1 to ng)
! ind_part      =>  star indexes in pm_commons(1 to np)
! ind_grid_part =>  points from star to grid (ind_grid) it resides in
! ng            =>  number of grids
! np            =>  number of stars
! ilevel        =>  amr level at which we're adding radiation
!-------------------------------------------------------------------------
    use amr_commons
    use pm_commons
    implicit none
    integer,intent(IN) ::ng,np,ilevel
    integer,dimension(1:nvector),intent(IN) ::ind_grid
    integer,dimension(1:nvector),intent(IN) ::ind_grid_part,ind_part
    !-----------------------------------------------------------------------
    integer::i,j,idim,nx_loc,ip
    real(dp)::dx,dx_loc,scale,vol_loc
    logical::error
    ! Grid based arrays
    real(dp),dimension(1:nvector,1:ndim),save::x0
    integer ,dimension(1:nvector),save::ind_cell
    integer ,dimension(1:nvector,1:threetondim),save::nbors_father_cells
    integer ,dimension(1:nvector,1:twotondim),save::nbors_father_grids
    ! Particle based arrays
    integer,dimension(1:nvector),save::igrid_son,ind_son
    logical,dimension(1:nvector),save::ok
    real(dp),dimension(1:nvector,1:ndim),save::x
    integer ,dimension(1:nvector,3),save::id=0,igd=0,icd=0
    integer ,dimension(1:nvector),save::igrid,icell,indp,kg
    real(dp),dimension(1:3)::skip_loc
    ! units and temporary quantities
    real(dp),parameter::vol_factor=2**ndim   ! Vol factor for ilevel-1 cells
!-------------------------------------------------------------------------

    ! Mesh spacing in ilevel
    dx = 0.5D0**ilevel
    nx_loc = (icoarse_max - icoarse_min + 1)
    skip_loc = (/0.0d0,0.0d0,0.0d0/)
    if(ndim>0)skip_loc(1) = dble(icoarse_min)
    if(ndim>1)skip_loc(2) = dble(jcoarse_min)
    if(ndim>2)skip_loc(3) = dble(kcoarse_min)
    scale = boxlen/dble(nx_loc) ! usually scale == 1
    dx_loc = dx*scale
    vol_loc = dx_loc**ndim

    ! Lower left corners of 3x3x3 grid-cubes (with given grid in center)
    do idim = 1, ndim
      do i = 1, ng
        x0(i,idim) = xg(ind_grid(i),idim) - 3.0D0*dx
      end do
    end do

    ! Gather 27 neighboring father cells (should be present anytime !)
    do i=1,ng
      ind_cell(i) = father(ind_grid(i))
    end do
    call get3cubefather(&
      ind_cell, nbors_father_cells, nbors_father_grids, ng, ilevel)
    ! now nbors_father cells are a cube of 27 cells with ind_cell in the
    ! middle and nbors_father_grids are the 8 grids that contain these 27
    ! cells (though only one of those is fully included in the cube)

    ! Rescale position of stars to positions within 3x3x3 cell supercube
    do idim = 1, ndim
      do j = 1, np
        x(j,idim) = xp(ind_part(j),idim)/scale + skip_loc(idim)
        x(j,idim) = x(j,idim) - x0(ind_grid_part(j),idim)
        x(j,idim) = x(j,idim)/dx
        ! so 0<x<2 is bottom cell, ...., 4<x<6 is top cell
      end do
    end do

    ! NGP at level ilevel
    do idim=1,ndim
      do j=1,np
        id(j,idim) = x(j,idim) ! So id=0-5 is the cell (in the
      end do                    ! 3x3x3 supercube) containing the star
    end do

    ! Compute parent grids
    do idim = 1, ndim
      do j = 1, np
        igd(j,idim) = id(j,idim)/2 ! must be 0, 1 or 2
      end do
    end do
    do j = 1, np
      kg(j) = 1 + igd(j,1) + 3*igd(j,2) + 9*igd(j,3) ! 1 to 27
    end do
    do j = 1, np
      igrid(j) = son(nbors_father_cells(ind_grid_part(j),kg(j)))
      ! grid (not cell) containing the star
    end do

    ! Check if particles are entirely in level ilevel.
    ! This should always be the case in post-processing
    ok(1:np) = .true.
    do j = 1, np
      ok(j) = ok(j) .and. igrid(j) > 0
    end do ! if ok(j) is true then particle j's cell contains a grid.
    ! Otherwise it is a leaf, and we need to fill it with radiation.

    ! Compute parent cell position within it's grid
    do idim = 1, ndim
      do j = 1, np
        if( ok(j) ) then
          icd(j,idim) = id(j,idim) - 2*igd(j,idim) ! 0 or 1
        end if
      end do
    end do
    do j = 1, np
      if( ok(j) ) then
        icell(j) = 1 + icd(j,1) + 2*icd(j,2) + 4*icd(j,3) ! 1 to 8
      end if
    end do

    ! Compute parent cell address
    do j = 1, np
      !cell index
      if( ok(j) )then
        indp(j) = ncoarse + (icell(j)-1)*ngridmax + igrid(j)   !ilevel
      else
        indp(j) = nbors_father_cells(ind_grid_part(j),kg(j))   !ilevel-1
      end if
    end do

    ! Add mass to cell density variables
    do j=1,np
      if( ok(j) ) then                                      !   ilevel cell
        if(is_DM(typep(ind_part(j)))) then !DM
          rhoprt(indp(j),1) = rhoprt(indp(j),1) + mp(ind_part(j))/vol_loc

        else if(is_star(typep(ind_part(j)))) then !Pop II star
          rhoprt(indp(j),2) = rhoprt(indp(j),2) + mp(ind_part(j))/vol_loc
        end if

      else                                                  ! ilevel-1 cell
        if(is_DM(typep(ind_part(j)))) then !DM
          rhoprt(indp(j),1) = rhoprt(indp(j),1) + mp(ind_part(j))/vol_loc/vol_factor

        else if(is_star(typep(ind_part(j)))) then !Pop II star
          rhoprt(indp(j),2) = rhoprt(indp(j),2) + mp(ind_part(j))/vol_loc/vol_factor
        end if
      endif

      ! !KS DEBUG
      ! print '(A, 4I8,1P2E12.3)', 'KS DEBUG (set_part_dens) myid, ilevel, indp, ind_part, rhoDM, rhostar: ', &
      !      myid, ilevel, indp(j), ind_part(j), rhoprt(indp(j),1), rhoprt(indp(j),2)
    end do

  end subroutine set_part_dens

