        if (nstep_restart >= 0) then
          write(nchar,'(I0)') nstep_restart
          command_long = 'cd '//TRIM(SubDir)//' && rm -f *.vtk.tmp; mkdir -p orphan_'//TRIM(nchar)// &
            ' && for f in *.*.*.vtk; do n=${f#*.}; n=${n%%.*}; case "$n" in ""|*[!0-9]*) continue;; esac;'// &
